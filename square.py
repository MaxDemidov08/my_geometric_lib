def area(a):
    '''
    Принимает число:
        a : длина стороны квадрата
    Возвращает значение площади квадрата со стороной a
        area(a)
    '''
    return a * a


def perimeter(a):
    '''
    Принимает число:
        a : длина стороны квадрата
    Возвращает значение периметра квадрата со стороной a
        perimeter(a)
    '''
    return 4 * a
