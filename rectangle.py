def area(a, b): 
    '''
    Принимает два числа:
        a : длинна одной стороны
        b : длинна другой стороны
    Возвращает значение площади прямоугольника со сторонами a,b
        area(a,b)
    '''
    return a * b 

def perimeter(a, b): 
    '''
    Принимает два числа:
        a : длинна одной стороны
        b : длинна другой стороны
    Возвращает значение периметра прямоугольника со сторонами a,b
        perimeter(a,b)
    '''
    return (a+b)*2 
